import type { Car } from "@/lib/ev/types";
import type { Faq } from "@/lib/ev/regionCopy";
import { NATIONAL_MAX } from "@/data/cars";

export interface CarContent {
  /** 누리집 "제조사+모델"(공백 제거·소문자)에서 같은 계열 트림을 고르는 정규식 */
  family: string;
  /** 차종 소개 문단 */
  intro: string[];
  /** 국비가 이렇게 산정된 배경 */
  points: string[];
  /** 구매 전 확인할 점 */
  tips: string[];
  /** 비교 대상 차종 (slug 와 한 줄 이유) */
  rivals: { slug: string; why: string }[];
  faq: Faq[];
}

type Build = (c: Car, of: (slug: string) => Car | undefined) => CarContent;

const won = (v: number | null | undefined) => (v === null || v === undefined ? "확인 필요" : `${v.toLocaleString("ko-KR")}만원`);
const nat = (c: Car) => won(c.national);
const conv = (c: Car) => (c.national === null ? "확인 필요" : won(c.national + NATIONAL_MAX.conversion));
const ratio = (c: Car) => (c.national === null ? null : Math.round((c.national / NATIONAL_MAX.large) * 100));
const km = (c: Car) => (c.range ? `${c.range}km` : "인증치 확인");

/** 공통 FAQ: 지방비 비례·전환지원금 (모든 차종에 붙는다) */
function commonFaq(c: Car): Faq[] {
  const r = ratio(c);
  return [
    {
      q: `${c.model} 지방비는 지역 표의 최대액을 그대로 받나요?`,
      a:
        r === null
          ? `아닙니다. 지방비는 차종별 국비 산정액이 상한 대비 몇 %인지에 비례해 지급됩니다. ${c.model}의 국비가 확정되면 그 비율만큼 거주지 지방비가 계산됩니다.`
          : `아닙니다. 지방비는 국비 산정액 비율에 비례합니다. ${c.model} ${c.trim}의 국비 ${nat(c)}은 승용 상한 ${NATIONAL_MAX.large}만원의 약 ${r}%이므로, 예를 들어 지방비 최대 400만원인 지역이라면 약 ${Math.round(400 * (r / 100))}만원을 받습니다.`,
    },
    {
      q: `${c.model}을(를) 사면서 기존 휘발유차를 폐차하면 얼마가 더 나오나요?`,
      a: `전환지원금 ${NATIONAL_MAX.conversion}만원이 국비에 더해집니다. 구매자 명의의 내연기관차를 폐차하거나 이전(양도)한 뒤 전기차를 출고·등록해야 하며, 지자체 공고에 따라 처분 시점 요건이 있으니 계약 전에 순서를 확인하세요.${c.national === null ? "" : ` 국비 ${nat(c)}에 더하면 ${conv(c)}이 됩니다.`}`,
    },
  ];
}

